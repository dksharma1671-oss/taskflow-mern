import axios from "axios";

// Backend base URL — .env me VITE_API_URL set kar sakte ho, warna localhost:5000 use hoga
const API_URL = import.meta.env.VITE_API_URL || "http://localhost:5000/api";

const api = axios.create({
  baseURL: API_URL,
});

// Har request ke saath automatically JWT token attach kar do (agar localStorage me hai)
api.interceptors.request.use((config) => {
  const token = localStorage.getItem("token");
  if (token) {
    config.headers.Authorization = `Bearer ${token}`;
  }
  return config;
});

// Agar kabhi 401 (unauthorized) mile to user ko login page pe bhej do
api.interceptors.response.use(
  (response) => response,
  (error) => {
    if (error.response && error.response.status === 401) {
      localStorage.removeItem("token");
      localStorage.removeItem("user");
      // Sirf tab redirect karo jab already login page pe na ho
      if (!window.location.pathname.includes("/login")) {
        window.location.href = "/login";
      }
    }
    return Promise.reject(error);
  }
);

export default api;
